create table public.donations (
  id uuid primary key default gen_random_uuid(),
  donor_id uuid not null references public.profiles(id) on delete cascade,
  total numeric(12,2) not null check (total >= 0),
  status text not null default 'confirmed'
    check (status in ('confirmed', 'cancelled')),
  created_at timestamptz not null default now()
);

create table public.donation_items (
  id bigint generated by default as identity primary key,
  donation_id uuid not null references public.donations(id) on delete cascade,
  product_id text not null,
  product_name text not null,
  foundation_id text not null,
  foundation_name text not null,
  quantity integer not null check (quantity > 0),
  unit_price numeric(12,2) not null check (unit_price >= 0)
);

create index donations_donor_created_idx
  on public.donations (donor_id, created_at desc);

create index donation_items_donation_idx
  on public.donation_items (donation_id);

alter table public.donations enable row level security;
alter table public.donation_items enable row level security;

grant select, insert on public.donations to authenticated;
grant select, insert on public.donation_items to authenticated;
grant usage, select on sequence public.donation_items_id_seq to authenticated;

create policy "Users can read own donations"
on public.donations
for select
to authenticated
using ((select auth.uid()) = donor_id);

create policy "Users can create own donations"
on public.donations
for insert
to authenticated
with check ((select auth.uid()) = donor_id);

create policy "Users can read own donation items"
on public.donation_items
for select
to authenticated
using (
  exists (
    select 1
    from public.donations d
    where d.id = donation_items.donation_id
      and d.donor_id = (select auth.uid())
  )
);

create policy "Users can add items to own donations"
on public.donation_items
for insert
to authenticated
with check (
  exists (
    select 1
    from public.donations d
    where d.id = donation_items.donation_id
      and d.donor_id = (select auth.uid())
  )
);

create or replace function public.create_donation(p_items jsonb)
returns uuid
language plpgsql
security invoker
set search_path = public
as $$
declare
  v_user_id uuid := auth.uid();
  v_donation_id uuid;
  v_total numeric(12,2);
begin
  if v_user_id is null then
    raise exception 'authentication required';
  end if;

  if p_items is null
     or jsonb_typeof(p_items) <> 'array'
     or jsonb_array_length(p_items) = 0 then
    raise exception 'donation must contain at least one item';
  end if;

  select coalesce(sum(x.quantity * x.unit_price), 0)
  into v_total
  from jsonb_to_recordset(p_items) as x(
    product_id text,
    product_name text,
    foundation_id text,
    foundation_name text,
    quantity integer,
    unit_price numeric
  );

  insert into public.donations (donor_id, total, status)
  values (v_user_id, v_total, 'confirmed')
  returning id into v_donation_id;

  insert into public.donation_items (
    donation_id, product_id, product_name, foundation_id,
    foundation_name, quantity, unit_price
  )
  select
    v_donation_id, x.product_id, x.product_name, x.foundation_id,
    x.foundation_name, x.quantity, x.unit_price
  from jsonb_to_recordset(p_items) as x(
    product_id text,
    product_name text,
    foundation_id text,
    foundation_name text,
    quantity integer,
    unit_price numeric
  );

  return v_donation_id;
end;
$$;

revoke execute on function public.create_donation(jsonb) from public;
revoke execute on function public.create_donation(jsonb) from anon;
grant execute on function public.create_donation(jsonb) to authenticated;
